-- Work requests and their timeline.
--
-- What lists filter and sort on is a column; the rest of the contract's
-- WorkRequest is one JSONB object in its own shape (camelCase keys), read and
-- written whole with the request: targetIds, targetOther, currentBehavior,
-- desiredBehavior, acceptanceCriteria, checklistSource, checklist, outOfScope,
-- attachments, desiredDateReason, precheck, infoRequest, rejectionReason,
-- report, scope, work, regression, verification, release.
--
-- Requests are never deleted (a cancelled one stays), so people and projects
-- are referenced with ON DELETE RESTRICT. Numbers start at 1.

create table requests (
    id           bigint generated by default as identity primary key,
    project_id   uuid not null references projects (id) on delete restrict,
    requester_id uuid not null references users (id) on delete restrict,
    assignee_id  uuid references users (id) on delete restrict,
    status       text not null check (status in (
                     'submitted', 'reporting', 'scope_check', 'review', 'info_needed', 'rejected', 'in_progress',
                     'code_review', 'verification', 'changes_requested', 'release_scheduled', 'done', 'cancelled')),
    type         text not null check (type in ('new_feature', 'change', 'bug', 'copy_design', 'non_code', 'checklist')),
    title        text not null,
    desired_date date,
    created_at   timestamptz not null default now(),
    updated_at   timestamptz not null default now(),
    details      jsonb not null check (jsonb_typeof(details) = 'object')
);

create index requests_requester_id_idx on requests (requester_id);
create index requests_assignee_id_idx on requests (assignee_id);
create index requests_project_id_idx on requests (project_id);
create index requests_status_idx on requests (status);
create index requests_updated_at_idx on requests (updated_at desc);

-- The timeline: append-only, in the order things happened (seq).
create table request_events (
    seq         bigint generated always as identity primary key,
    id          uuid not null unique default gen_random_uuid(),
    request_id  bigint not null references requests (id) on delete cascade,
    at          timestamptz not null default now(),
    actor_type  text not null check (actor_type in ('user', 'ai', 'system')),
    actor_id    uuid references users (id) on delete restrict,
    event       text not null,
    from_status text,
    to_status   text,
    note        text,
    check ((actor_type = 'user') = (actor_id is not null))
);

create index request_events_request_id_idx on request_events (request_id, seq);
